local count=0
local function test(name, fn) fn(); count=count+1; print("ok "..name) end
local function snapshot(extra)
    local value={now=1000,valid=true,items={["existing-id"]=true},hunger=0.4,thirst=0.5}
    for key,item in pairs(extra or {}) do value[key]=item end
    return value
end
test("loot needs actual distinct inventory additions after the queue is empty",function()
    local tracker=ClaudeActionEvidence.new()
    tracker:begin(1,"LOOT",snapshot())
    local changed=snapshot({items={["existing-id"]=true,["new-id"]=true}})
    assert(tracker:update(changed,1,1100).status=="pending")
    local result=tracker:update(changed,0,1200)
    assert(result.status=="observed_effect" and result.added==1 and result.seq==1 and result.action=="LOOT")
end)
test("empty queues without inventory changes are not loot success",function()
    local tracker=ClaudeActionEvidence.new(); tracker:begin(2,"LOOT",snapshot())
    assert(tracker:update(snapshot(),0,1100).status=="pending")
    local result=tracker:update(snapshot(),0,2100)
    assert(result.status=="no_effect" and result.added==0)
end)
test("food success requires a hunger decrease and retains full precision",function()
    local tracker=ClaudeActionEvidence.new(); tracker:begin(3,"EAT",snapshot())
    local result=tracker:update(snapshot({hunger=0.399}),0,1100)
    assert(result.status=="observed_effect" and result.hungerDrop>0.0009 and result.thirstDrop==0)
end)
test("water success requires a thirst decrease",function()
    local tracker=ClaudeActionEvidence.new(); tracker:begin(4,"DRINK",snapshot())
    local result=tracker:update(snapshot({thirst=0.2}),0,1100)
    assert(result.status=="observed_effect" and math.abs(result.thirstDrop-0.3)<0.000001)
end)
test("food and drink cannot succeed from the other stat or tiny rounding noise",function()
    for _,action in ipairs({"EAT","DRINK"}) do
        local tracker=ClaudeActionEvidence.new(); tracker:begin(5,action,snapshot())
        local noEffect=action=="EAT" and snapshot({hunger=0.39999,thirst=0.1}) or snapshot({hunger=0.1,thirst=0.49999})
        assert(tracker:update(noEffect,0,1100).status=="pending")
        assert(tracker:update(noEffect,0,2100).status=="no_effect")
    end
end)
test("unreadable current or baseline snapshots cannot claim effects or no effect",function()
    local tracker=ClaudeActionEvidence.new(); tracker:begin(6,"LOOT",snapshot())
    assert(tracker:update(snapshot({valid=false,items={["new-id"]=true}}),0,2000).status=="pending")
    assert(tracker:update(snapshot({valid=false}),0,31000).status=="unverified")
    tracker:begin(7,"EAT",snapshot({valid=false}))
    assert(tracker:update(snapshot({hunger=0}),0,2000).status=="pending")
    assert(tracker:update(snapshot({hunger=0}),0,31000).status=="unverified")
end)
test("manual revocation remains interrupted even when the cleared queue has changed inventory",function()
    local tracker=ClaudeActionEvidence.new(); tracker:begin(8,"LOOT",snapshot())
    tracker:cancel("manual_takeover")
    local result=tracker:update(snapshot({items={["new-id"]=true}}),0,2000)
    assert(result.status=="interrupted" and result.detail=="manual_takeover" and result.added==0)
end)
test("baseline inventory is copied rather than aliased",function()
    local before=snapshot(); local tracker=ClaudeActionEvidence.new(); tracker:begin(9,"LOOT",before)
    before.items["new-id"]=true
    assert(tracker:update(before,0,1100).added==1)
end)
test("a queue that stays busy times out unverified",function()
    local tracker=ClaudeActionEvidence.new(); tracker:begin(10,"LOOT",snapshot())
    local result=tracker:update(snapshot({items={["new-id"]=true}}),1,31000)
    assert(result.status=="unverified" and result.detail=="observation_timeout")
end)
test("no pending operation cannot overwrite an existing completed receipt",function()
    local tracker=ClaudeActionEvidence.new(); assert(tracker:update(snapshot(),0,1100)==nil)
    tracker:begin(11,"DRINK",snapshot()); tracker:update(snapshot({thirst=0.1}),0,1100)
    local result=tracker.receipt
    assert(tracker:begin(12,"MOVE",snapshot())==nil)
    assert(tracker:update(snapshot(),0,2000)==result and result.status=="observed_effect")
    tracker:cancel("later_manual_input"); assert(result.status=="observed_effect")
end)
test("multiplayer synchronization can deliver a delayed effect after the queue empties",function()
    local tracker=ClaudeActionEvidence.new(); tracker:begin(13,"LOOT",snapshot())
    assert(tracker:update(snapshot(),0,1100).status=="pending")
    assert(tracker:update(snapshot(),0,1600).status=="pending")
    assert(tracker:update(snapshot({items={["new-id"]=true}}),0,1800).status=="observed_effect")
end)
test("no-effect grace restarts if a busy action resumes",function()
    local tracker=ClaudeActionEvidence.new(); tracker:begin(14,"EAT",snapshot())
    tracker:update(snapshot(),0,1100); tracker:update(snapshot(),1,1500)
    assert(tracker:update(snapshot(),0,2100).status=="pending")
    assert(tracker:update(snapshot(),0,3099).status=="pending")
    assert(tracker:update(snapshot(),0,3100).status=="no_effect")
end)
test("minimum settle time and invalid clocks cannot report immediate effects",function()
    local tracker=ClaudeActionEvidence.new(); tracker:begin(15,"EAT",snapshot())
    assert(tracker:update(snapshot({hunger=0}),0,1020).status=="pending")
    assert(tracker:update(snapshot({hunger=0}),0,1050).status=="observed_effect")
    tracker:begin(16,"EAT",snapshot({now=0/0})); assert(tracker.receipt.status=="unverified")
    tracker:begin(17,"EAT",snapshot()); assert(tracker:update(snapshot(),0,999).status=="unverified")
end)
print("passed "..count.." action evidence Lua tests")
